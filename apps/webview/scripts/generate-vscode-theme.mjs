#!/usr/bin/env node
/**
 * Regenerates src/styles/vscode-theme.css.
 *
 *   node scripts/generate-vscode-theme.mjs
 *
 * VS Code injects each theme colour into webviews as `--vscode-<id>`, dots
 * turned into dashes. This maps every one to a Tailwind v4 colour token, so
 * `bg-vscode-editor-background` follows the active theme.
 *
 * Replaces @githubocto/tailwind-vscode, a Tailwind v3 plugin archived on
 * 2026-08-06.
 */
import { writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const REFERENCE = 'https://code.visualstudio.com/api/references/theme-color';
const OUT = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'src',
  'styles',
  'vscode-theme.css',
);

/** Top-level ids that carry no dot, so the dotted-id pattern cannot find them. */
const DOTLESS = [
  'foreground',
  'disabledForeground',
  'errorForeground',
  'descriptionForeground',
  'focusBorder',
  'contrastBorder',
  'contrastActiveBorder',
  'selection.background',
  'widget.shadow',
  'icon.foreground',
];

// The reference page uses two shapes: `<li><code>` and `<li><p><code>`.
const DOTTED = /<li[^>]*>\s*(?:<p[^>]*>\s*)?<code[^>]*>([^<]+)<\/code>/g;
const COLOR_ID = /^[A-Za-z][A-Za-z0-9]*(\.[A-Za-z0-9]+)+$/;

const response = await fetch(REFERENCE);
if (!response.ok) throw new Error(`${REFERENCE} -> ${response.status}`);
const html = await response.text();

const ids = new Set(DOTLESS);
for (const [, id] of html.matchAll(DOTTED)) {
  const key = id.trim();
  if (COLOR_ID.test(key)) ids.add(key);
}

const sorted = [...ids].toSorted();
const lines = sorted.map((id) => {
  const token = id.replaceAll('.', '-');
  return `  --color-vscode-${token}: var(--vscode-${token});`;
});

const css = `/*
 * GENERATED by scripts/generate-vscode-theme.mjs - do not edit.
 * Source: ${REFERENCE}
 * ${sorted.length} theme colours.
 *
 * \`inline\`, so utilities use var(--vscode-*) directly and unused colours
 * emit nothing.
 */
@theme inline {
${lines.join('\n')}
}
`;

await writeFile(OUT, css, 'utf8');
console.log(`wrote ${sorted.length} colours to ${OUT}`);
